// ЗАВДАННЯ №1: Оголоси глобальну константу VERSION (тип f32) зі значенням 1.5
// Напиши тут: const ...

fn main() {
    println!("--- ІНІЦІАЛІЗАЦІЯ ВІДНОВЛЕННЯ ДАНИХ ---");

    // ЗАВДАННЯ №2: Виправ помилку типу. Ідентифікатор має бути цілим числом (u32).
    let agent_id: u32 = 404; // Зміни значення на свій номер

    // ЗАВДАННЯ №3: Додай мутабельність. Це значення має змінюватися!
    let mut system_load = 50; 
    system_load = system_load + 25;

    // ЗАВДАННЯ №4: Використай правильний тип для точності (f64).
    let reactor_temp: f64 = 98.6;

    // ЗАВДАННЯ №5: Тіньове перекриття (Shadowing). 
    // Перетвори 'access_code' з рядка на число (його довжину).
    let access_code = "ALPHA_9";
    let access_code = access_code.len(); // Тут використай let знову

    // ЗАВДАННЯ №6: Символи. Збережи логотип Rust '🦀' у змінну типу char.
    let os_logo: char = '🦀';

    // ЗАВДАННЯ №7: Кортеж (Tuple). Віднови координати (x, y, z).
    // Заповни нулі реальними даними: (f64, f64, i32)
    let coordinates = (45.5, 10.2, 500);

    // ЗАВДАННЯ №8: Масив (Array). Створи масив 'status_bits' з 5 елементів i32.
    // Усі елементи мають бути рівні 1.
    let status_bits = [1; 5];

    // --- БЛОК ДІАГНОСТИКИ (Не змінювати) ---
    println!("Версія протоколу: {}", 1.5); // Заміни 1.5 на константу VERSION у Завданні 7
    println!("Агент ID: {}", agent_id);
    println!("Навантаження: {}%", system_load);
    println!("Температура: {} C", reactor_temp);
    println!("Довжина коду: {}", access_code);
    println!("Логотип: {}", os_logo);
    println!("Локація: x={}, z={}", coordinates.0, coordinates.2);
    println!("Біт статусу 3: {}", status_bits[2]);
    println!("--- ВІДНОВЛЕННЯ ЗАВЕРШЕНО ---");
}
