section .data
    ; Ініціалізовані дані
    data1 dd 100   ; Наш пакет даних
    key   dd 42    ; Наш ключ шифрування

section .bss
    ; Неініціалізовані дані (тут ми резервуємо місце)
    ; resd 1 = Reserve 1 Doubleword (зарезервувати 4 байти)
    ; Це наш "сховок". На старті програми тут лежить сміття.
    
    result resd 1

section .text
    global _start     ; Глобальна точка входу

_start:

    ; -- ЧАСТИНА 1: Обчислення --
    ;
    ; Мета: EAX = data1 + key
    ;
    ;   +-----------------+
    ;   |       EAX       |
    ;   | 0x00000000      |
    ;   +-----------------+
    ;
    ;   [data1] = 100
    ;   [key]   = 42
    
    mov   eax, [data1]    ; EAX = 100
    add   eax, [key]      ; EAX = 100 + 42 = 142
    
    ;
    ; ПЕРЕВІРКА (в GDB): `info registers eax` має показати 142 (0x8e)
    ;

    ; -- ЧАСТИНА 2: Збереження у Сховок --
    ;
    ; Мета: Зберегти результат (142) з EAX у наш сховок 'result'.
    ;
    ;   +-----------------+        +-----------------+
    ;   |       EAX       |        |     [result]    | (Пам'ять)
    ;   | 142             |  --->  | 0 (або сміття)  |
    ;   +-----------------+        +-----------------+
    ;
    ; ЗАВДАННЯ: Використовуйте MOV, щоб зберегти значення EAX
    ;           *всередину* комірки 'result'.
    
    mov   [???], eax      ; ЗАВДАННЯ: [result] = EAX

    ;
    ; ПЕРЕВІРКА (в GDB): `x /d &result` має показати 142.
    ;

    ; -- ЧАСТИНА 3: Отримання Координат Сховку --
    ;
    ; Мета: Зберегти *адресу* сховку 'result' у регістр EBX.
    ; Ми НЕ використовуємо [ ] дужки, бо нам потрібна сама мітка.
    ;
    ;   +-----------------+        +-----------------+
    ;   |       EBX       |        |     result      | (Мітка/Адреса)
    ;   | 0x00000000      |  <---  | (напр. 0x804a008) |
    ;   +-----------------+        +-----------------+
    ;
    ; ЗАВДАННЯ: Використовуйте MOV, щоб завантажити *адресу* 'result' в EBX.
    
    mov   ebx, ???        ; ЗАВДАННЯ: EBX = result (адреса, НЕ значення)

    ;
    ; ПЕРЕВІРКА (в GDB): `info registers ebx` та `p &result`
    ;                   мають показати однакове значення (адресу).
    ;

    ; -- ЧАСТИНA 4: Завершення програми --
    ;
    ; Стандартний вихід
    
    mov   eax, 1          ; sys_exit
    mov   ebx, 0          ; код 0 (success)
    int   0x80            ; виклик ядра
