; ======================================================================
; Лабораторна робота №3: Інформаційний Сховок (Data Stash) (32-bit)
; Ваше завдання: заповнити ???, щоб виконати збереження в пам'ять.
; ======================================================================

section .data
    ; Ця секція для *ініціалізованих* даних.
    ; Ми визначаємо наші константи тут.
    ; dd = Define Doubleword (одне "подвійне слово" = 32 біти = 4 байти)
    
    first_num  dd 100  ; Наше перше число
    second_num dd 42   ; Наше друге число

section .bss
    ; Ця секція для *неініціалізованих* даних (резервування пам'яті).
    ; Тут ми резервуємо місце для нашого сховку.
    ; resd = REServe Doubleword (зарезервувати одне подвійне слово)
    
    result resd 1      ; Резервуємо 1 подвійне слово (4 байти) для результату

section .text
    global _start     ; Глобальна точка входу, видима для компонувальника

; ======================================================================
; ГОЛОВНА ЛОГІКА ПРОГРАМИ
; ======================================================================
_start:

    ; -- ЧАСТИНА 1: Обчислення (ADD) --
    ;
    ; Наша мета: додати first_num (100) та second_num (42).
    ; Результат збережемо в EAX.
    ;
    ; Регістри - це швидкісні "комірки" всередині процесора.
    ;
    ;   +-----------------+
    ;   |       EAX       |  <-- Акумулятор (тут буде результат 100 + 42)
    ;   +-----------------+
    ;   |       EBX       |  <-- Базовий (тут буде адреса сховку)
    ;   +-----------------+
    
    ; Крок 1.1: Завантажити перше число в EAX.
    ; Інструкція MOV <куди>, <що>
    ; [ ] - квадратні дужки означають "взяти значення, що лежить 
    ;       за адресою 'first_num'".
    
    mov   eax, [first_num]    ; EAX = 100
    
    ; Крок 1.2: Додати друге число до EAX.
    ; Інструкція ADD <куди>, <що>
    ; Виконує: <куди> = <куди> + <що>
    
    add   eax, [second_num]   ; EAX = EAX + 42 = 142
    
    ;
    ; ПЕРЕВІРКА: Якщо ви все зробили правильно, EAX тепер має містити 142 (100 + 42).
    ; Перевірте це у GDB командою: info registers eax
    ;

    ; -- ЧАСТИНА 2: Збереження в Пам'ять (MOV [адреса], значення) --
    ;
    ; Наша мета: зберегти значення з EAX (142) у комірку пам'яті 'result'.
    ;
    ; Пам'ять - це великий масив байтів. Кожен байт має свою адресу.
    ; Ми резервували комірку 'result' у секції .bss.
    ;
    ; [ ] - квадратні дужки означають "записати/прочитати *всередину* пам'яті"
    ;       (тобто за адресою, що вказана всередині дужок).
    ;
    ; ЗАВДАННЯ: Заповніть ???, щоб зберегти значення EAX у комірку result.
    ; Підказка: Нам потрібні [ ] дужки, щоб вказати, що ми пишемо всередину пам'яті.
    
    mov   [???], eax          ; ЗАВДАННЯ (ЧАСТИНА 2): Запишіть EAX у комірку 'result'
    
    ;
    ; ПЕРЕВІРКА: Після виконання цієї інструкції, значення 142 має бути записане
    ; у комірку пам'яті 'result'. Ми перевіримо це у GDB пізніше.
    ;

    ; -- ЧАСТИНА 3: Отримання Адреси (LEA або MOV без [ ]) --
    ;
    ; Наша мета: завантажити *адресу* комірки 'result' (а не її вміст!) у EBX.
    ;
    ; Це важливо: 
    ;   - mov ebx, [result]  ; завантажує ВМІСТ (значення 142)
    ;   - mov ebx, result    ; завантажує АДРЕСУ (напр. 0x804a008)
    ;
    ; Нам потрібна саме адреса, щоб ми могли повідомити "координати сховку".
    ;
    ; ЗАВДАННЯ: Заповніть ???, щоб завантажити адресу 'result' у EBX.
    ; Підказка: Нам НЕ потрібні [ ] дужки, бо ми беремо саму "мітку" (адресу).
    
    mov   ebx, ???            ; ЗАВДАННЯ (ЧАСТИНА 3): Завантажте адресу 'result' у EBX
    
    ;
    ; ПЕРЕВІРКА: Якщо ви все зробили правильно, EBX тепер має містити адресу
    ; комірки 'result'. Перевірте це у GDB командами:
    ;   (gdb) p &result          ; покаже адресу result
    ;   (gdb) info registers ebx ; покаже вміст EBX (має збігатися з адресою)
    ;

    ; -- ЧАСТИНA 4: Завершення програми --
    ;
    ; Ми використовуємо той самий код, що й у попередніх лабах
    ; для чистого виходу з програми.
    ;
    ; Системний виклик sys_exit (номер 1)
    ; void _exit(int status);
    
    mov   eax, 1          ; Номер системного виклику sys_exit.
    mov   ebx, 0          ; Код завершення 0 (успіх).
    int   0x80            ; Виклик ядра (переривання).
