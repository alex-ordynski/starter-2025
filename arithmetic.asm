; ======================================================================
; Лабораторна робота №2: Проста арифметика (32-bit)
; Ваше завдання: заповнити ???, щоб виконати обчислення.
; ======================================================================

section .data
    ; Ця секція для *ініціалізованих* даних.
    ; Ми визначаємо наші константи тут.
    ; dd = Define Doubleword (одне "подвійне слово" = 32 біти = 4 байти)
    
    first_num  dd 25   ; Наше перше число
    second_num dd 17   ; Наше друге число

section .bss
    ; Ця секція для *неініціалізованих* даних (резервування пам'яті).
    ; В цій лабі вона нам не потрібна.
    ; Приклад:
    ;   my_buffer resb 1024  ; резервуємо 1024 байти

section .text
    global _start     ; Глобальна точка входу, видима для компонувальника

; ======================================================================
; ГОЛОВНА ЛОГІКА ПРОГРАМИ
; ======================================================================
_start:

    ; -- ЧАСТИНА 1: Додавання (ADD) --
    ;
    ; Наша мета: додати first_num (25) та second_num (17).
    ; Результат збережемо в EAX.
    ;
    ; Регістри - це швидкісні "комірки" всередині процесора.
    ;
    ;   +-----------------+
    ;   |       EAX       |  <-- Акумулятор (тут буде результат 25 + 17)
    ;   +-----------------+
    ;   |       EBX       |  <-- Базовий (ми завантажимо сюди одне з чисел)
    ;   +-----------------+
    
    ; Крок 1.1: Завантажити перше число в EAX.
    ; Інструкція MOV <куди>, <що>
    ; [ ] - квадратні дужки означають "взяти значення, що лежить 
    ;       за адресою 'first_num'".
    
    mov   eax, [first_num]    ; EAX = 25
    
    ; Крок 1.2: Завантажити друге число в EBX.
    ; ЗАВДАННЯ: Заповніть ???
    
    mov   ebx, [???]          ; ЗАВДАННЯ: завантажте 'second_num' в EBX

    ; Крок 1.3: Додати EBX до EAX.
    ; Інструкція ADD <куди>, <що>
    ; Виконує: <куди> = <куди> + <що>
    ; ЗАВДАННЯ: Заповніть ???
    
    add   eax, ???            ; ЗАВДАННЯ: додайте EBX до EAX
    
    ;
    ; ПЕРЕВІРКА: Якщо ви все зробили правильно, EAX тепер має містити 42 (25 + 17).
    ; Перевірте це у GDB командою: info registers eax
    ;

    ; -- ЧАСТИНА 2: Віднімання (SUB) --
    ;
    ; Наша мета: відняти second_num (17) від first_num (25).
    ; Результат збережемо в EDX, щоб не затерти EAX.
    ;
    ;   +-----------------+
    ;   |       EAX       |  (Містить 42)
    ;   +-----------------+
    ;   |       EDX       |  <-- Дані (тут буде результат 25 - 17)
    ;   +-----------------+

    ; Крок 2.1: Завантажити перше число в EDX.
    ; ЗАВДАННЯ: Заповніть ???
    
    mov   edx, ???            ; ЗАВДАННЯ: завантажте 'first_num' в EDX

    ; Крок 2.2: Відняти друге число від EDX.
    ; Інструкція SUB <куди>, <що>
    ; Виконує: <куди> = <куди> - <що>
    ; Ми можемо віднімати значення прямо з пам'яті:
    
    sub   edx, [second_num] ; EDX = EDX - 17
    
    ;
    ; ПЕРЕВІРКА: Якщо ви все зробили правильно, EDX тепер має містити 8 (25 - 17).
    ; Перевірте це у GDB командою: info registers edx
    ;

    ; -- ЧАСТИНA 3: Завершення програми --
    ;
    ; Ми використовуємо той самий код, що й у "Hello, world!"
    ; для чистого виходу з програми.
    ;
    ; Системний виклик sys_exit (номер 1)
    ; void _exit(int status);
    
    mov   eax, 1          ; Номер системного виклику sys_exit.
    mov   ebx, 0          ; Код завершення 0 (успіх).
    int   0x80            ; Виклик ядра (переривання).
