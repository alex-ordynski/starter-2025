DROP TABLE IF EXISTS owl_post;
DROP TABLE IF EXISTS magic_incidents;
DROP TABLE IF EXISTS muggle_sightings;

-- Таблиця 1: Совина пошта
CREATE TABLE owl_post (
    post_id INTEGER PRIMARY KEY AUTOINCREMENT,
    sender TEXT,
    recipient TEXT NOT NULL,
    subject TEXT,
    message_body TEXT,
    delivery_status TEXT CHECK(delivery_status IN ('Доставлено', 'Перехоплено', 'Загублено')),
    interception_risk INTEGER,
    delivery_date DATE
);

-- Таблиця 2: Лог магічних інцидентів
CREATE TABLE magic_incidents (
    incident_id INTEGER PRIMARY KEY AUTOINCREMENT,
    location TEXT NOT NULL,
    spell_used TEXT,
    intensity INTEGER,
    incident_time DATETIME,
    is_underage BOOLEAN,
    suspect_name TEXT
);

-- Таблиця 3: Скарги маґлів
CREATE TABLE muggle_sightings (
    sighting_id INTEGER PRIMARY KEY AUTOINCREMENT,
    observer_name TEXT,
    location TEXT,
    description TEXT,
    sighting_date DATE,
    memory_modified BOOLEAN
);

